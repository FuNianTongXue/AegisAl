export function normalizeClientLocale(language?: string): ClientLocale {
  if (language === "zh-Hant") return "zh-Hant";
  if (language === "en") return "en";
  return "zh-Hans";
}

export function clientLocaleTag(locale: ClientLocale) {
  if (locale === "en") return "en-US";
  if (locale === "zh-Hant") return "zh-Hant";
  return "zh-CN";
}

export function translate(locale: ClientLocale, source: string, replacements?: Replacements) {
  const dictionary = locale === "en" ? english : locale === "zh-Hant" ? traditional : undefined;
  let value = dictionary?.[source] || source;
  Object.entries(replacements || {}).forEach(([key, replacement]) => {
    value = value.replaceAll(`{${key}}`, String(replacement));
  });
  return value;
}

export function useI18n() {
  const locale = useAppStore((state) => normalizeClientLocale(state.settings?.preferences?.language));
  const t = useCallback((source: string, replacements?: Replacements) => translate(locale, source, replacements), [locale]);
  return { locale, t };
}
